import mesa
import model.agent_defaults
import numpy as np
import model.enums
import model.entropy

from typing import Self, TYPE_CHECKING, Tuple
from model.success import CommunicationContext

if TYPE_CHECKING:
    from model.model import ReductionModel


def scores_to_entropy(log_scores: np.ndarray):
    score_probabilities = np.exp(log_scores)
    decision_entropy = model.entropy.compute_entropy(
        score_probabilities / np.sum(score_probabilities)
    )

    return decision_entropy


class ReductionAgent(mesa.Agent):
    """A speaker in the model"""

    def __init__(self, reduction_model: "ReductionModel"):
        """Initialise a ReductionModel agent

        Args:
            reduction_model (ReductionModel):
            The ReductionModel for which the agent is initialised
        """

        # Pass the parameters to the parent class.
        super().__init__(reduction_model)
        self.model: "ReductionModel" = reduction_model

        # Populate the agent's parameters based off the model parameters
        self.atts = model.agent_defaults.Attributes(
            vocabulary=self.model.params.vocabulary
        )

    def interact_do(self):
        # Choose a random other agent that is not the agent itself
        hearer_agent = self.model.get_random_agent(self)

        # If there *is* an interaction, do interact
        self.interact(hearer_agent)

    def interact(self, hearer_agent: Self):
        # Choose a random construction based on the selected probabilities
        # Also, save this in the tracker
        chosen_construction_index = self.model.get_random_construction_index()
        self.model.tracker.register_construction_chosen(chosen_construction_index)

        # Now, generate a vector for that specific construction
        vector = self.atts.vocabulary.get_construction_vector(
            chosen_construction_index, self.model.params.nprandom
        )
        vector_difference = (
            vector - self.atts.vocabulary.means[chosen_construction_index, :]
        )
        self.model.tracker.register_vector_difference(
            chosen_construction_index, vector_difference
        )

        # Check whether we are going to reduce
        do_reduction = (
            self.model.params.nprandom.random() < self.model.params.reduction_prob
        )
        # Check if we're already at value floor. If not, do not reduce any further!
        # Else we make sigma explode
        if np.mean(vector <= self.model.params.value_floor):
            do_reduction = False  # no further reduction please!

        # If so, reduce with the specified reduction method, else pass
        if do_reduction:
            reduced_vector = self.model.params.reduction.get_reduced_vector(vector)
        else:
            reduced_vector = vector

        reentrance_used = False
        if self.model.params.reentrance_entropy_floor > 0 and do_reduction:
            win_index, log_scores = self.get_construction_winner(reduced_vector)
            decision_entropy = scores_to_entropy(log_scores)
            self.model.tracker.register_decision_entropy_reentrance(decision_entropy)

            # If the win index does not match the chosen construction index,
            # we do not understand ourselves and we reverse the reduction
            if decision_entropy >= self.model.params.reentrance_entropy_floor:
                reduced_vector = vector
                do_reduction = False
                reentrance_used = True
        self.model.tracker.communicative_success.register_reentrance_usage(
            int(reentrance_used), chosen_construction_index
        )

        # Round?
        reduced_vector = np.round(reduced_vector)

        # Now, the other agent "hears" the construction that we just chose
        hearer_agent.receive_construction(
            reduced_vector, chosen_construction_index, do_reduction, reentrance_used
        )

    def get_construction_winner(
        self, heard_vector: np.ndarray
    ) -> Tuple[int, np.ndarray]:
        # First, we calculate the log probabilities
        # For each ctx, we check the probability that this vector was generated by that ctx
        log_scores = self.atts.vocabulary.calculate_log_score(heard_vector)

        # Which construction has the highest score?
        win_index = np.argmax(log_scores)

        return int(win_index), log_scores

    # update vocabulary distributions etc.
    def receive_construction(
        self,
        heard_vector: np.ndarray,
        true_construction_index: int,
        is_reduced: bool,
        reentrance_used: bool,
    ):
        win_index, log_scores = self.get_construction_winner(heard_vector)

        # What is the highest score?
        max_score = np.max(log_scores)
        # Compute difference with max score
        exp_scores = np.exp(log_scores - max_score)
        # Turn into weights
        weights = exp_scores / np.sum(exp_scores)

        # The entropy of the current decision
        # How certain are we making this decision?
        decision_entropy = scores_to_entropy(log_scores)
        self.model.tracker.register_decision_entropy(decision_entropy)

        communication_successful = true_construction_index == win_index

        if self.model.params.do_update:
            if self.model.params.to_update == model.enums.ToUpdate.DISTRIBUTED:
                pass
            elif self.model.params.to_update == model.enums.ToUpdate.WINNER_ONLY:
                # If feedback is enabled, do not update when communication is not successful
                if (
                    self.model.params.feedback_type
                    == model.enums.FeedbackTypes.FEEDBACK
                    and not communication_successful
                ):
                    pass
                else:
                    # Discriminatory force implementation
                    if (
                        decision_entropy
                        < self.model.params.discriminatory_entropy_floor
                        or self.model.params.discriminatory_entropy_floor == 0
                    ):
                        # Update only the winner with full weights
                        self.atts.vocabulary.observe_utterance(
                            int(win_index), heard_vector
                        )

                    if (
                        len(self.atts.vocabulary.batch_memory[win_index])
                        >= self.model.params.batch_size
                    ):
                        self.atts.vocabulary.update_distribution(
                            win_index, learning_rate=self.model.params.learning_rate
                        )
            else:
                raise ValueError("Unknown update destination")

        self.model.tracker.communicative_success.register_communication_outcome(
            int(communication_successful),
            true_construction_index,
            CommunicationContext.ANY,
        )
        self.model.tracker.register_win_index(int(win_index), true_construction_index)

        if is_reduced:
            self.model.tracker.communicative_success.register_communication_outcome(
                int(communication_successful),
                true_construction_index,
                CommunicationContext.REDUCING,
            )

        if reentrance_used:
            self.model.tracker.communicative_success.register_communication_outcome(
                int(communication_successful),
                true_construction_index,
                CommunicationContext.REENTRANCE,
            )
